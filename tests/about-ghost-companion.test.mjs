import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {mountAboutGhost} from '../js/about-ghost-companion.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
test('ghost is decorative and confined to the motto row before the original portrait',()=>{
 const html=read('index.html'),css=read('css/about-ghost-companion.css');
 const row=html.slice(html.indexOf('<span class="about-motto-row">'),html.indexOf('<figure class="about-particle-portrait"'));
 assert.match(row,/IS MY MOTTO[\s\S]*data-about-ghost aria-hidden="true"/);
 assert.equal((row.match(/shape-rendering="crispEdges"/g)||[]).length,6);
 assert.doesNotMatch(row,/<(?:button|a|canvas|img)\b/);
 for(const tone of ['pink','ink','red'])assert.ok(row.includes('about-ghost-heart--'+tone));
 assert.match(css,/pointer-events:none/);assert.match(css,/prefers-reduced-motion:reduce/);
});
test('visibility and accessibility gate idle animations and cleanup',()=>{
 const attrs=new Set();const root={setAttribute:k=>attrs.add(k),removeAttribute:k=>attrs.delete(k),toggleAttribute:(k,v)=>v?attrs.add(k):attrs.delete(k)};
 const win=new EventTarget(),doc=new EventTarget(),media=new EventTarget();doc.hidden=false;media.matches=false;
 win.document=doc;win.matchMedia=()=>media;
 let notify,disconnected=false;
 win.IntersectionObserver=class{constructor(cb){notify=cb}observe(){}disconnect(){disconnected=true}};
 const dispose=mountAboutGhost(root,win);
 assert.ok(!attrs.has('data-ghost-active'));assert.ok(!attrs.has('data-ghost-seen'));
 notify([{isIntersecting:true}]);assert.ok(attrs.has('data-ghost-active'));assert.ok(attrs.has('data-ghost-seen'));
 doc.hidden=true;doc.dispatchEvent(new Event('visibilitychange'));assert.ok(!attrs.has('data-ghost-active'));
 doc.hidden=false;doc.dispatchEvent(new Event('visibilitychange'));assert.ok(attrs.has('data-ghost-active'));
 media.matches=true;media.dispatchEvent(new Event('change'));assert.ok(!attrs.has('data-ghost-active'));
 media.matches=false;media.dispatchEvent(new Event('change'));assert.ok(attrs.has('data-ghost-active'));
 notify([{isIntersecting:false}]);assert.ok(!attrs.has('data-ghost-active'));assert.ok(attrs.has('data-ghost-seen'));
 dispose();assert.ok(disconnected);assert.ok(!attrs.has('data-ghost-managed'));
});
